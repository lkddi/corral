/**
 * nginx 管理（Spec §4.4 vhost 自动生成）
 *
 * 设计：每站点一份独立 conf（`nginx/sites/<name>.conf`），主配置由 daemon 全量生成，
 * 站点增删只改单文件 + reload —— 不做行内 patch，避免配置腐化。
 *
 * 端口纪律：listen 用配置端口（默认 80 需提权）。端口被占时返回 PORT_CONFLICT
 * 并带占用进程名 + PID（Spec §9 错误态要求，禁只说「端口被占用」）。
 */

import { promises as fs } from 'node:fs';
import path from 'node:path';
import type { CorralConfig, CorralPaths } from '../config.js';
import type { SiteRecord } from '../daemon/state.js';
import { isPortInUse, pidAlive, run, spawnDetached, waitFor, which } from '../util/exec.js';

export interface NginxStatus {
  running: boolean;
  pid: number | null;
  binary: string | null;
}

export interface PortOwner {
  pid: number;
  command: string;
}

/** 谁占着这个端口（PORT_CONFLICT 的归因，Spec §9） */
export async function portOwner(port: number): Promise<PortOwner | null> {
  const r = await run('/usr/sbin/lsof', ['-nP', `-iTCP:${port}`, '-sTCP:LISTEN', '-Fpc'], { timeoutMs: 5_000 });
  if (r.code !== 0 || !r.stdout.trim()) return null;
  let pid = 0;
  let command = '';
  for (const line of r.stdout.split('\n')) {
    if (line.startsWith('p')) pid = Number.parseInt(line.slice(1), 10);
    else if (line.startsWith('c')) command = line.slice(1);
  }
  return pid ? { pid, command } : null;
}

const MIME_TYPES = [
  'types {',
  '  text/html html htm;',
  '  text/css css;',
  '  application/javascript js mjs;',
  '  application/json json;',
  '  image/svg+xml svg svgz;',
  '  image/png png;',
  '  image/jpeg jpg jpeg;',
  '  image/gif gif;',
  '  image/webp webp;',
  '  image/x-icon ico;',
  '  font/woff woff;',
  '  font/woff2 woff2;',
  '  application/pdf pdf;',
  '  text/plain txt md;',
  '  application/xml xml;',
  '  application/zip zip;',
  '  video/mp4 mp4;',
  '}',
].join('\n');

export class NginxManager {
  constructor(
    private readonly paths: CorralPaths,
    private readonly cfg: CorralConfig,
  ) {}

  private pidPath(): string {
    return path.join(this.paths.runtimeDir, 'nginx.pid');
  }

  /** 二进制探测：config 指定 → PATH → 随包 runtime/nginx */
  async resolveBin(): Promise<string | null> {
    if (this.cfg.nginxBin) {
      return (await fs.access(this.cfg.nginxBin).then(() => true, () => false)) ? this.cfg.nginxBin : null;
    }
    const onPath = await which('nginx');
    if (onPath) return onPath;
    for (const rel of ['nginx', 'nginx/nginx', 'sbin/nginx']) {
      const p = path.join(this.paths.runtimeDir, rel);
      if (await fs.access(p).then(() => true, () => false)) return p;
    }
    return null;
  }

  siteConfPath(siteName: string): string {
    return path.join(this.paths.sitesConfDir, `${siteName}.conf`);
  }

  /** 主配置（全量重写：唯一真源是 state，不做增量 patch） */
  async renderMain(): Promise<void> {
    await fs.mkdir(this.paths.nginxDir, { recursive: true });
    await fs.mkdir(this.paths.sitesConfDir, { recursive: true });
    await fs.mkdir(this.paths.logsDir, { recursive: true });
    for (const sub of ['client', 'proxy', 'fastcgi']) {
      await fs.mkdir(path.join(this.paths.runtimeDir, 'nginx-temp', sub), { recursive: true });
    }
    await fs.writeFile(path.join(this.paths.nginxDir, 'mime.types'), `${MIME_TYPES}\n`, 'utf8');

    const tmp = path.join(this.paths.runtimeDir, 'nginx-temp');
    const conf = [
      '# Corral-managed nginx.conf — regenerated by the daemon, do not edit',
      'worker_processes 1;',
      `pid ${this.pidPath()};`,
      `error_log ${path.join(this.paths.logsDir, 'nginx-error.log')} warn;`,
      '',
      'events {',
      '  worker_connections 1024;',
      '}',
      '',
      'http {',
      `  include ${path.join(this.paths.nginxDir, 'mime.types')};`,
      '  default_type application/octet-stream;',
      `  access_log ${path.join(this.paths.logsDir, 'nginx-access.log')};`,
      '  sendfile on;',
      '  keepalive_timeout 65;',
      '  server_names_hash_bucket_size 128;',
      '  client_max_body_size 64m;',
      '  gzip on;',
      '  gzip_types text/css application/javascript application/json image/svg+xml;',
      '',
      `  client_body_temp_path ${path.join(tmp, 'client')};`,
      `  proxy_temp_path ${path.join(tmp, 'proxy')};`,
      `  fastcgi_temp_path ${path.join(tmp, 'fastcgi')};`,
      '  # 注：不生成 uwsgi/scgi temp path —— 精简 nginx 构建常裁掉这两个模块，',
      '  # 生成它们会让 `nginx -t` 直接 emerg，且 Corral 只用 fastcgi 一种上游。',
      '',
      '  # 未知 Host 兜底：明确 404 而不是落到某个站点（防串站）',
      '  server {',
      `    listen ${this.cfg.httpPort} default_server;`,
      '    server_name _;',
      '    return 404;',
      '  }',
      '',
      `  include ${path.join(this.paths.sitesConfDir, '*.conf')};`,
      '}',
      '',
    ].join('\n');
    await fs.writeFile(this.paths.nginxConf, conf, 'utf8');
  }

  /** 站点 vhost（root + fastcgi 直连该站点 PHP 版本的 unix socket） */
  async writeSite(site: SiteRecord, phpSocket: string): Promise<void> {
    await fs.mkdir(this.paths.sitesConfDir, { recursive: true });
    const host = `${site.name}.${this.cfg.tld}`;
    const listen = site.port && site.port !== this.cfg.httpPort ? site.port : this.cfg.httpPort;
    const conf = [
      `# Corral-managed vhost for ${site.name} — regenerated on link/unlink`,
      'server {',
      `  listen ${listen};`,
      `  server_name ${host};`,
      `  root ${site.path};`,
      '  index index.php index.html index.htm;',
      '',
      '  location / {',
      '    try_files $uri $uri/ /index.php?$query_string;',
      '  }',
      '',
      '  location ~ \\.php$ {',
      `    fastcgi_pass unix:${phpSocket};`,
      '    fastcgi_index index.php;',
      '    fastcgi_split_path_info ^(.+\\.php)(/.+)$;',
      '    fastcgi_param SCRIPT_FILENAME $document_root$fastcgi_script_name;',
      '    fastcgi_param PATH_INFO $fastcgi_path_info;',
      '    fastcgi_param QUERY_STRING $query_string;',
      '    fastcgi_param REQUEST_METHOD $request_method;',
      '    fastcgi_param CONTENT_TYPE $content_type;',
      '    fastcgi_param CONTENT_LENGTH $content_length;',
      '    fastcgi_param REQUEST_URI $request_uri;',
      '    fastcgi_param DOCUMENT_URI $document_uri;',
      '    fastcgi_param DOCUMENT_ROOT $document_root;',
      '    fastcgi_param SERVER_PROTOCOL $server_protocol;',
      '    fastcgi_param GATEWAY_INTERFACE CGI/1.1;',
      '    fastcgi_param SERVER_SOFTWARE nginx;',
      '    fastcgi_param REMOTE_ADDR $remote_addr;',
      '    fastcgi_param REMOTE_PORT $remote_port;',
      '    fastcgi_param SERVER_ADDR $server_addr;',
      '    fastcgi_param SERVER_PORT $server_port;',
      `    fastcgi_param SERVER_NAME ${host};`,
      '    fastcgi_param REDIRECT_STATUS 200;',
      '    fastcgi_read_timeout 120s;',
      '  }',
      '',
      '  location ~ /\\.(?!well-known) { deny all; }',
      '}',
      '',
    ].join('\n');
    await fs.writeFile(this.siteConfPath(site.name), conf, 'utf8');
  }

  async removeSite(siteName: string): Promise<void> {
    await fs.rm(this.siteConfPath(siteName), { force: true });
  }

  async test(): Promise<{ ok: boolean; output: string }> {
    const bin = await this.resolveBin();
    if (!bin) return { ok: false, output: 'nginx binary not found (set CORRAL_NGINX_BIN or install nginx)' };
    const r = await run(bin, ['-t', '-p', this.paths.nginxDir, '-c', this.paths.nginxConf], { timeoutMs: 15_000 });
    return { ok: r.code === 0, output: `${r.stdout}${r.stderr}`.trim() };
  }

  async running(): Promise<NginxStatus> {
    let pid: number | null = null;
    try {
      const raw = Number.parseInt((await fs.readFile(this.pidPath(), 'utf8')).trim(), 10);
      if (pidAlive(raw)) pid = raw;
    } catch {
      /* no pid file */
    }
    return { running: pid !== null, pid, binary: await this.resolveBin() };
  }

  async start(): Promise<{ started: boolean; code?: 'PORT_CONFLICT' | 'PERMISSION_DENIED'; reason?: string; owner?: PortOwner }> {
    if ((await this.running()).running) return { started: true };
    const bin = await this.resolveBin();
    if (!bin) return { started: false, reason: 'nginx binary not found (set CORRAL_NGINX_BIN or install nginx)' };

    await this.renderMain();
    const t = await this.test();
    if (!t.ok) return { started: false, reason: t.output };

    const owner = await portOwner(this.cfg.httpPort);
    if (owner) return { started: false, code: 'PORT_CONFLICT', owner, reason: `${owner.command} (pid ${owner.pid}) already listens on :${this.cfg.httpPort}` };

    spawnDetached(bin, ['-p', this.paths.nginxDir, '-c', this.paths.nginxConf]);
    const up = await waitFor(async () => (await this.running()).running && (await isPortInUse(this.cfg.httpPort)), 8_000);
    if (!up) {
      const log = await fs.readFile(path.join(this.paths.logsDir, 'nginx-error.log'), 'utf8').catch(() => '');
      const tail = log.trim().split('\n').slice(-3).join(' | ');
      if (/Permission denied|bind\(\) to/i.test(tail)) return { started: false, code: 'PERMISSION_DENIED', reason: tail };
      return { started: false, reason: tail || 'nginx did not start' };
    }
    return { started: true };
  }

  async stop(): Promise<boolean> {
    const st = await this.running();
    if (!st.running || !st.pid) return false;
    try {
      process.kill(st.pid, 'SIGQUIT');
    } catch {
      return false;
    }
    await waitFor(async () => !pidAlive(st.pid!), 5_000);
    await fs.rm(this.pidPath(), { force: true });
    return true;
  }

  /** 配置变更后热加载；未运行则返回 false（调用方决定是否拉起） */
  async reload(): Promise<boolean> {
    const bin = await this.resolveBin();
    const st = await this.running();
    if (!bin || !st.running || !st.pid) return false;
    const r = await run(bin, ['-p', this.paths.nginxDir, '-c', this.paths.nginxConf, '-s', 'reload'], { timeoutMs: 10_000 });
    return r.code === 0;
  }
}
